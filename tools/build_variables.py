#!/usr/bin/env python3
"""Regenerate assets/variables.js from a linux-vitals checkout.

Usage: tools/build_variables.py /path/to/linux-vitals

meta/argument_specs.yml is the authoritative source for every role variable
(tests/test_argument_specs.py on main keeps it in step with defaults/main.yml),
so the command builder reads nothing else.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROLES = [
    ("vitals_scan", "Scan", "Read-only discovery. Always runs."),
    ("vitals_heal", "Heal", "Opt-in. One restart per enabled, failed unit."),
    ("vitals_certs", "Certs", "Opt-in. The only role that opens an outbound connection."),
    ("vitals_report", "Report", "Snapshot, compare, render, notify, gate."),
]

# name -> (is a credential, .env key it falls back to). The argument specs say
# this in prose only, so it is kept here rather than guessed from wording.
CREDENTIALS = {
    "linux_vitals_slack_webhook_url": (True, "SLACK_WEBHOOK_URL"),
    "linux_vitals_email_host": (False, "EMAIL_SMTP_HOST"),
    "linux_vitals_email_username": (True, "EMAIL_SMTP_USERNAME"),
    "linux_vitals_email_password": (True, "EMAIL_SMTP_PASSWORD"),
    "linux_vitals_generic_webhook_url": (True, "GENERIC_WEBHOOK_URL"),
    "linux_vitals_generic_webhook_headers": (True, None),
}


def markup(text: str) -> str:
    # ansible-doc markup -> the backtick code spans the builder renders.
    text = re.sub(r"[CVOI]\(([^)]*)\)", r"`\1`", text)
    return re.sub(r"\s+", " ", text).strip()


def main(collection: Path, out: Path) -> None:
    roles = []
    total = 0
    for role_id, label, blurb in ROLES:
        spec = yaml.safe_load((collection / "roles" / role_id / "meta" / "argument_specs.yml").read_text())
        options = spec["argument_specs"]["main"].get("options", {})
        rows = []
        for name, opt in options.items():
            desc = opt.get("description", "")
            if isinstance(desc, list):
                desc = " ".join(desc)
            secret, env = CREDENTIALS.get(name, (False, None))
            rows.append({
                "name": name,
                "type": opt.get("type", "str"),
                "default": opt.get("default"),
                "choices": opt.get("choices"),
                "description": markup(desc),
                "secret": secret,
                "env": env,
            })
        total += len(rows)
        roles.append({"id": role_id, "label": label, "blurb": blurb, "vars": rows})

    galaxy = yaml.safe_load((collection / "galaxy.yml").read_text())
    body = json.dumps({"version": galaxy["version"], "roles": roles}, indent=2, default=str)
    out.write_text(
        "// Generated by tools/build_variables.py from the collection's role argument specs -- do not edit by hand.\n"
        f"// {total} variables across {len(roles)} roles, collection {galaxy['version']}.\n"
        "// meta/argument_specs.yml is the authoritative source: tests/test_argument_specs.py\n"
        "// fails if it disagrees with a role's defaults/main.yml.\n"
        f"window.LV_DATA = {body};\n"
    )
    print(f"wrote {out}: {total} variables")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(__file__).resolve().parents[1] / "assets" / "variables.js")
