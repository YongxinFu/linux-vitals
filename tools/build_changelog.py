#!/usr/bin/env python3
"""Regenerate assets/changelog.js from a linux-vitals checkout's CHANGELOG.md.

Usage: tools/build_changelog.py /path/to/linux-vitals

GitHub Releases only carries some versions (2.0.0 and 1.3.x were tagged
without one), so the site's timeline is built from the changelog, and the live
API only adds release links on top.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HEADING = re.compile(r"^## \[(?P<version>[^\]]+)\](?: - (?P<date>\d{4}-\d{2}-\d{2}))?", re.M)
SECTION = re.compile(r"^### (.+)$", re.M)
BOLD_BULLET = re.compile(r"^- \*\*(.+?)\*\*", re.M | re.S)
LINK = re.compile(r"\[([^\]]+)\]\([^)]+\)")


def clean(text: str) -> str:
    text = LINK.sub(r"\1", text)
    text = re.sub(r"\*+", "", text)
    return re.sub(r"\s+", " ", text).strip().rstrip(".")


def main(collection: Path, out: Path) -> None:
    text = (collection / "CHANGELOG.md").read_text()
    heads = list(HEADING.finditer(text))
    entries = []
    for i, head in enumerate(heads):
        body = text[head.end(): heads[i + 1].start() if i + 1 < len(heads) else len(text)]
        sections = {}
        parts = SECTION.split(body)
        intro = parts[0]
        for name, chunk in zip(parts[1::2], parts[2::2]):
            sections[name.strip()] = len(re.findall(r"^- ", chunk, re.M))
        highlights = [clean(m) for m in BOLD_BULLET.findall(body)]
        if not highlights:
            highlights = [clean(m) for m in re.findall(r"^- (.+)$", body, re.M)][:3]
        summary = clean(intro.strip().split("\n\n")[0]) if intro.strip() else ""
        entries.append({
            "version": head["version"],
            "date": head["date"],
            "summary": summary,
            "sections": sections,
            "highlights": highlights[:6],
        })
    out.write_text(
        "// Generated by tools/build_changelog.py from CHANGELOG.md -- do not edit by hand.\n"
        f"window.LV_CHANGELOG = {json.dumps(entries, indent=1, ensure_ascii=False)};\n"
    )
    print(f"wrote {out}: {len(entries)} entries")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(Path(sys.argv[1]), Path(__file__).resolve().parents[1] / "assets" / "changelog.js")
